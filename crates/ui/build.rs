//! Embeds `assets/` into the binary and generates the `IconName` enum from
//! `assets/icons/*.svg` (decision 0024).

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("assets");
    println!("cargo:rerun-if-changed=assets");
    let mut files = Vec::new();
    collect(&root, &root, &mut files);
    files.sort();

    let mut table = String::from("pub(crate) static ASSETS: &[(&str, &[u8])] = &[\n");
    for rel in &files {
        let abs = root.join(rel).display().to_string().replace('\\', "/");
        let _ = writeln!(table, "    ({rel:?}, include_bytes!({abs:?})),");
    }
    table.push_str("];\n");

    let mut icons: Vec<String> = files
        .iter()
        .filter_map(|f| {
            f.strip_prefix("icons/")?
                .strip_suffix(".svg")
                .map(str::to_owned)
        })
        .collect();
    icons.sort();
    let mut enum_src = String::from(
        "/// Every Lucide icon bundled in `assets/icons` (generated by build.rs).\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub enum IconName {\n",
    );
    for icon in &icons {
        let _ = writeln!(enum_src, "    {},", pascal(icon));
    }
    enum_src.push_str("}\n\nimpl IconName {\n    /// Every icon, in file-name order.\n    pub const ALL: &[IconName] = &[\n");
    for icon in &icons {
        let _ = writeln!(enum_src, "        IconName::{},", pascal(icon));
    }
    enum_src.push_str("    ];\n\n    /// Asset path of the SVG.\n    pub fn path(self) -> &'static str {\n        match self {\n");
    for icon in &icons {
        let _ = writeln!(
            enum_src,
            "            IconName::{} => \"icons/{icon}.svg\",",
            pascal(icon)
        );
    }
    enum_src.push_str("        }\n    }\n}\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(out.join("assets_table.rs"), table).unwrap();
    std::fs::write(out.join("icon_names.rs"), enum_src).unwrap();
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<String>) {
    for entry in std::fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        if path.is_dir() {
            collect(root, &path, out);
        } else {
            let rel = path
                .strip_prefix(root)
                .unwrap()
                .to_string_lossy()
                .replace('\\', "/");
            out.push(rel);
        }
    }
}

fn pascal(name: &str) -> String {
    name.split('-')
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}
